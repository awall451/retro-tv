"""Build a compact Batocera Control Center stylesheet for the 640x480 Trinitron profile.

Usage: python3 make_bcc_compact_css.py <system style.css> <output style.css> [font_px]
At 640x480 the Control Center still picks its "scale-full" layout, whose padding, minimum
widths and 16px text overflow the screen. This copies the stock stylesheet, then re-applies
every ".scale-small ..." rule to ".scale-full ..." as well, sets the text size, and drops the
remaining minimum widths. The Control Center reads it from /userdata/system/configs/controlcenter/.
"""
import re
import sys

src, out = sys.argv[1], sys.argv[2]
font_px = int(sys.argv[3]) if len(sys.argv) > 3 else 12
css = open(src).read()

extra = ["\n/* ---- Trinitron 640x480: compact layout (generated by make_bcc_compact_css.py) ---- */"]
for selector, body in re.findall(r"([^{}]*\.scale-small[^{}]*)\{([^}]*)\}", css):
    selector = selector.strip()
    if "font-size" in body and selector.endswith("*"):
        continue  # text size set below
    full = ", ".join(s.strip().replace(".scale-small", ".scale-full") for s in selector.split(","))
    extra.append(f"{full} {{{body}}}")

# CRT legibility over 480i composite: bold strokes (thin 1-px lines flicker between the two
# interlaced fields) and bright values (composite smears saturated colors like the stock blue).
extra.append(f".scale-full * {{ font-size: {font_px}px; font-weight: bold; }}")
extra.append(".scale-full .value, .scale-full .value * { color: #fff3b0; }")
extra.append(".scale-full .header, .scale-full .item-text, .scale-full .group-title,"
             " .scale-full button > label { color: #ffffff; }")
extra.append(".scale-full button, .scale-full button.cc-tab, .scale-full button.cc-toggle,"
             " .scale-full .vgroup-cell-first, .scale-full .vgroup-row .value { min-width: 0; }")
extra.append(".scale-full button.cc-tab, .scale-full button.cc-tab:checked { padding: 4px 8px; }")
# Bold text widens the layout; tighten spacing so it stays inside 640 px with even side margins.
extra.append(".scale-full .vgroup-cell { padding: 3px 4px; }")
extra.append(".scale-full .vgroup-row { padding: 1px 0; }")
extra.append(".scale-full .group-frame { padding: 4px 6px; margin: 4px 0; }")
extra.append(".scale-full .cc-progressbar { min-width: 120px; }")
extra.append(".scale-full button { padding: 3px 6px; }")
# The tab content box starts indented but stretches to the window's full width, so its right
# border hung off-screen. A matching right margin brings it back inside with even sides.
extra.append(".scale-full .group-frame { margin-right: 32px; }")
open(out, "w").write(css + "\n".join(extra) + "\n")
print(f"wrote {out}: {len(extra) - 1} extra rules, text {font_px}px")
