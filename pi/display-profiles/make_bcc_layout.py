"""Build a Batocera Control Center layout without the Plane Mode toggle.

Usage: python3 make_bcc_layout.py <system controlcenter.xml> <output controlcenter.xml>
Plane Mode stops Bluetooth (and Wi-Fi), which disconnects the wireless controller you would
need to switch it back on. The Control Center reads /userdata/system/configs/controlcenter/
controlcenter.xml before the stock one, so this writes a copy with that feature removed.
Rebuilt from the stock file on every profile switch, so Batocera updates carry over.
"""
import re
import sys

src, out = sys.argv[1], sys.argv[2]
xml = open(src).read()
xml, n = re.subn(r'[ \t]*<feature display="Plane Mode".*?</feature>[ \t]*\n', "", xml, flags=re.S)
if n != 1:
    sys.exit(f"expected one Plane Mode feature in {src}, found {n}")
open(out, "w").write("<!-- Generated by make_bcc_layout.py from the stock layout: Plane Mode removed -->\n" + xml)
print(f"wrote {out}: Plane Mode removed")
